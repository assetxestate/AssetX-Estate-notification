export const txForAssessment = (assessmentType) => TX_FOR_ASSESSMENT[assessmentType] || null

const STATUS_RANK = { yes: 1, check: 2, no: 3 }

export function deedVerdict(key, assessmentType) {
  const type = deedTypeOf(key)
  const tx = txForAssessment(assessmentType)
  if (!type || !tx) return null
  const entry = type.tx[tx]
  const severity = entry.s === 'no' ? 'critical' : entry.s === 'check' ? (entry.level || 'medium') : null
  return { key, tx, txLabel: TX_LABELS[tx], status: entry.s, statusLabel: TX_STATUS[entry.s].label, icon: TX_STATUS[entry.s].icon, note: entry.note, severity, blocks: entry.s === 'no' }
}

// ประเภทย่อยของทรัพย์ที่บอกประเภทเอกสารอยู่แล้ว (เลือก "ที่ดินเปล่า (ส.ค.1)" = เอกสาร ส.ค.1)
const SUBTYPE_DEED = { 'ที่ดินเปล่า (น.ส.3)': 'ns3', 'ที่ดินเปล่า (ส.ค.1)': 'sk1', 'คอนโดมิเนียม': 'condo', 'อาคารชุด': 'condo' }
export const deedTypeForSubtype = (subtype) => SUBTYPE_DEED[subtype] || null

// ค่า titleType เดิม (valuationOptions TITLE_TYPES) — ยังเป็นตัวคิดคะแนน จึงแปลงไป-กลับให้คะแนนเท่าเดิม
export const LEGACY_TITLE = {
  chanoteFree: 'โฉนด (Chanote) ปลอดภาระ',
  chanoteMortgaged: 'โฉนด มีจำนองอยู่ชั้นเดียว',
  ns3k: 'น.ส.3ก (NS3G)',
  ns3: 'น.ส.3 (NS3)',
  severe: 'มีภาระ/ข้อพิพาทรุนแรง',
}

export const TITLE_ENCUMBRANCES = [
  { value: 'free', label: 'ปลอดภาระ' },
  { value: 'mortgaged', label: 'ติดจำนองเดิมอยู่ชั้นเดียว (ไถ่ถอนวันจด)' },
  { value: 'severe', label: 'มีภาระ/ข้อพิพาทรุนแรง' },
]

export function splitLegacyTitleType(titleType) {
  switch (titleType) {
    case LEGACY_TITLE.chanoteMortgaged: return { deedType: 'chanote', encumbrance: 'mortgaged' }
    case LEGACY_TITLE.ns3k: return { deedType: 'ns3k', encumbrance: 'free' }
    case LEGACY_TITLE.ns3: return { deedType: 'ns3', encumbrance: 'free' }
    case LEGACY_TITLE.severe: return { deedType: null, encumbrance: 'severe' }
    case LEGACY_TITLE.chanoteFree: return { deedType: 'chanote', encumbrance: 'free' }
    default: return { deedType: null, encumbrance: 'free' }
  }
}

// ประเภทเอกสารของแปลงหนึ่ง: เลือกไว้เอง → ประเภทย่อยที่บอกเอกสาร → titleType เดิม (ร่างเก่า) → โฉนด
export function deedTypeKeyFor(deed = {}, form = {}) {
  if (deed?.docType && DEED_BY_KEY[deed.docType]) return deed.docType
  return deedTypeForSubtype(form?.propertySubtype) || splitLegacyTitleType(form?.titleType).deedType || DEFAULT_DEED_TYPE
}

export function formDeedTypeKeys(form = {}) {
  const deeds = Array.isArray(form?.deeds) && form.deeds.length ? form.deeds : [{}]
  return [...new Set(deeds.map((d) => deedTypeKeyFor(d, form)))]
}

// ประเภทที่ทำธุรกรรมนี้ได้ยากที่สุดในชุด (ไม่มีธุรกรรม = ดูขายฝากแทน) · เสมอกันใช้ลำดับใน DEED_TYPES (หลัง = จำกัดกว่า)
export function strictestDeedType(keys = [], assessmentType) {
  const tx = txForAssessment(assessmentType) || 'khaifak'
  const order = (k) => DEED_TYPES.findIndex((t) => t.key === k)
  const valid = keys.filter((k) => DEED_BY_KEY[k])
  if (!valid.length) return DEFAULT_DEED_TYPE
  return valid.reduce((best, k) => {
    const a = STATUS_RANK[DEED_BY_KEY[k].tx[tx].s]
    const b = STATUS_RANK[DEED_BY_KEY[best].tx[tx].s]
    return a > b || (a === b && order(k) > order(best)) ? k : best
  })
}

export function formEncumbrance(form = {}) {
  return TITLE_ENCUMBRANCES.some((e) => e.value === form?.titleEncumbrance) ? form.titleEncumbrance : splitLegacyTitleType(form?.titleType).encumbrance
}

export function legacyTitleType(deedKey, encumbrance = 'free') {
  if (encumbrance === 'severe') return LEGACY_TITLE.severe
  const scoreAs = DEED_BY_KEY[deedKey]?.scoreAs || 'title'
  if (scoreAs === 'ns3k') return LEGACY_TITLE.ns3k
  if (scoreAs === 'ns3') return LEGACY_TITLE.ns3
  if (scoreAs === 'severe') return LEGACY_TITLE.severe
  return encumbrance === 'mortgaged' ? LEGACY_TITLE.chanoteMortgaged : LEGACY_TITLE.chanoteFree
}

// titleType ที่ใช้คิดคะแนน — ข้อมูลที่สอดคล้องกันได้ค่าเดิมทุกกรณี · ต่างจากเดิมเฉพาะร่างที่ประเภทย่อยบอกว่า น.ส.3/ส.ค.1 แต่เลือก "โฉนด" ไว้
export function effectiveTitleType(form = {}) {
  return legacyTitleType(strictestDeedType(formDeedTypeKeys(form), form?.assessmentType), formEncumbrance(form))
}

// ธงสำหรับ underwritingPolicy — แทนธง titleType เดิม
export function deedPolicyFlags(form = {}) {
  const flags = []
  const tx = txForAssessment(form?.assessmentType)
  for (const key of formDeedTypeKeys(form)) {
    const type = DEED_BY_KEY[key]
    const verdict = deedVerdict(key, form?.assessmentType)
    if (verdict && verdict.status !== 'yes') {
      flags.push({
        key: `deed:${key}`,
        label: `${type.code}: ${verdict.txLabel}${verdict.status === 'no' ? 'ไม่ได้' : 'ได้แบบมีเงื่อนไข'}`,
        severity: verdict.severity,
        blocks: verdict.blocks,
        condition: verdict.note,
      })
    } else if (type.review || (!tx && type.scoreAs !== 'title')) {
      flags.push({ key: `deed:${key}`, label: `เอกสาร ${type.code}`, severity: 'medium', condition: type.review || 'ต้องตรวจเอกสารสิทธิ์และข้อจำกัดการโอน/บังคับหลักประกัน' })
    }
  }
  const encumbrance = formEncumbrance(form)
  if (encumbrance === 'mortgaged') flags.push({ key: 'encumbrance:mortgaged', label: 'ติดจำนองเดิม', severity: 'medium', condition: 'ขอยอดหนี้จากผู้รับจำนองเดิม แล้วไถ่ถอนในวันเดียวกันก่อนจด — จำนองติดไปกับทรัพย์ (ป.พ.พ. ม.702 วรรคสอง)' })
  if (encumbrance === 'severe') flags.push({ key: 'encumbrance:severe', label: 'มีภาระ/ข้อพิพาทรุนแรง', severity: 'high', condition: 'ต้องตรวจเอกสารสิทธิ์และข้อจำกัดการโอน/บังคับหลักประกัน' })
  return flags
}

// เงื่อนไขตรวจก่อนวันจดของเอกสารในชุด
export function deedChecks(form = {}) {
  return [...new Set(formDeedTypeKeys(form).flatMap((key) => DEED_BY_KEY[key]?.checks || []))]
}

// ข้อความสั้นสำหรับบันทึกผลประเมิน (คอลัมน์ risks) และสรุปความเสี่ยง — ว่าง = โฉนดปลอดภาระ ทำธุรกรรมได้ปกติ
export function deedRiskText(form = {}) {
  return deedPolicyFlags(form).map((f) => f.label).join(', ')
}

export function deedSource(ref) {
  const src = DEED_SOURCES[ref?.src]
  if (!src) return null
  const official = ref.c ? ref.c === 'official' : src.official
  return { ...src, at: ref.at, official }
}
