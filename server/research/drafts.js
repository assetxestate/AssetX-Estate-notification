export function isGenericPageToken(token, brand = {}) {
  const vocab = [...PAGE_VOCAB, ...THAI_PLACES, ...(brand.service_area || []), ...(brand.services || []), ...(brand.property_types || [])]
    .map((w) => String(w).trim()).filter(Boolean).sort((a, b) => b.length - a.length)
  let rest = String(token || '')
  let prev
  do { prev = rest; for (const w of vocab) rest = rest.split(w).join('') } while (rest !== prev && rest.length > 1)
  return rest.length <= 1
}

// โทเค็นไทย (≥ 4 ตัวอักษร) ของชื่อเพจในป้าย "Facebook · <เพจ>" / "Meta Ad Library · <เพจ>" ที่เป็นชื่อแบรนด์/ชื่อคน (ไม่ใช่คำบริการ) และโมเดลรู้จักได้
// — ต้องอยู่ในข้อเท็จจริงด้วย (ชื่อเพจไม่ถูกส่งให้ AI ทางเดียวที่โมเดลรู้คือแอด/โพสต์เอ่ยชื่อตัวเอง · คลังแอดจริง 96/182 ชิ้นเป็นแบบนั้น 7 พ.ย. 2569)
// การลบป้ายทั้งก้อนใน parseDraft จับไม่ได้เมื่อโมเดลเขียนชื่อแบรนด์เป็นคำเดี่ยว ("ทุนที่ดิน" จาก "ทุนที่ดิน รับจำนอง ขายฝาก") และ foreignNamesIn จับเฉพาะชื่อละติน
export function pageBrandTokens(label = '', facts = '', brand = {}) {
  const haystack = String(facts || '')
  const parts = String(label || '').split(/\s*·\s*/).map((p) => p.trim()).filter((p) => p && !/^(facebook|meta ad library)$/i.test(p))
  const out = new Set()
  for (const part of parts) {
    for (const raw of part.split(/\s+/)) {
      const t = raw.replace(/[()"'“”.,!]/g, '').replace(/^(เพจ|บริษัท|บจก|หจก|บมจ|โดย)/, '')
      if (!/^[ก-๙]{4,}$/.test(t) || isGenericPageToken(t, brand) || !haystack.includes(t)) continue
      out.add(t)
    }
  }
  return [...out]
}

