export function foreignNamesIn(facts = '') {
  const names = new Set()
  for (const m of String(facts || '').matchAll(/[A-Za-z][A-Za-z.&'-]{2,}(?:\s+[A-Za-z][A-Za-z.&'-]{1,})*/g)) {
    const name = m[0].trim()
    if (name.length < 3 || GENERIC_LATIN.has(name.toLowerCase())) continue
    names.add(name)
  }
  return [...names]
}
