// กลุ่มคนอ่านของเพจ — เจ้าของเลือก 9 พ.ย. 2569: "เจ้าของทรัพย์ต้องการเงิน (A) อย่างเดียว"
// ที่มา: โปสเตอร์ร่าง #27 อ่านแล้วไม่รู้ว่าพูดกับ "คนทำธุรกิจด้วยกัน" หรือ "สอนลูกค้า" — ไอเดีย 36 ใน 39 ใบติดหลายกลุ่มหรือไม่ติดเลย
// ตัวเขียนจึงได้รายชื่อทั้ง A–D แล้วเขียนปนมุมคนปล่อยเงิน ("หากผู้ขายฝากเป็นบุคคลธรรมดา…" "ราคาที่รองรับทำเล")
//
// brand.page_audience = รหัสกลุ่มที่เพจพูดด้วย (ไม่ระบุ = A) · ทุกโพสต์พูดกับ "กลุ่มเดียว" เสมอ (targetAudience)
// ไอเดียที่ติดป้ายกลุ่มแต่ไม่มีกลุ่มของเพจเลย (เช่น ข่าวตลาด B/C/D) = ไม่ใช่เรื่องของคนอ่านเรา → ตัวเก็บข้าม · คิวตั้งหมดอายุ (store.planExpiry)
// ไม่มี import: angles.js / drafts.js / collector.js / store.js ใช้ร่วมกันได้โดยไม่วนกัน

export const DEFAULT_PAGE_AUDIENCE = ['A']

export function pageAudience(brand = {}) {
  const codes = Array.isArray(brand?.page_audience) ? brand.page_audience.filter((c) => typeof c === 'string' && c.trim()).map((c) => c.trim()) : []
  return codes.length ? codes : DEFAULT_PAGE_AUDIENCE
}

// กลุ่มเดียวที่โพสต์นี้พูดด้วย: กลุ่มแรกของไอเดียที่อยู่ในกลุ่มของเพจ · ไม่มีเลย = กลุ่มแรกของเพจ
export function targetAudience(idea = {}, brand = {}) {
  const page = pageAudience(brand)
  const own = Array.isArray(idea?.audience) ? idea.audience : []
  return own.find((code) => page.includes(code)) || page[0]
}

// ไม่ติดป้ายกลุ่ม = เรื่องทั่วไป เขียนให้กลุ่มของเพจได้ · ติดป้ายแต่ไม่มีกลุ่มของเพจ = ไม่ใช่เรื่องของคนอ่านเรา
export function fitsPageAudience(codes, brand = {}) {
  const own = Array.isArray(codes) ? codes.filter(Boolean) : []
  if (!own.length) return true
  const page = pageAudience(brand)
  return own.some((code) => page.includes(code))
}

// บริการที่เพจพูดถึง (brand.page_services) — ไม่ระบุ = ทุกบริการของแบรนด์
export function pageServices(brand = {}) {
  return Array.isArray(brand?.page_services) && brand.page_services.length ? brand.page_services : (brand?.services || [])
}

// ประโยคบอกบทบาทธุรกิจในบรรทัดแรกของ prompt (มุมเล่า + ร่าง)
export function businessLine(brand = {}) {
  const page = pageAudience(brand)
  return page.length === 1 && page[0] === 'A' ? 'ธุรกิจขายฝาก/จำนองในไทย' : 'ธุรกิจขายฝาก/จำนอง/นายหน้าอสังหาริมทรัพย์ในไทย'
}

// พื้นที่ให้บริการในคำของโพสต์ (เจ้าของ 10 พ.ย. 2569: เริ่มที่กรุงเทพฯ และปริมณฑลก่อน วางแผนขยายทั่วประเทศ)
// service_area = รายชื่อจังหวัด (เป็นคำให้คะแนนกลุ่ม area ของเรดาร์ด้วย) · service_area_label = ชื่อที่อ่านเป็นธรรมชาติในโพสต์
export function serviceAreaLabel(brand = {}) {
  return String(brand.service_area_label || '').trim() || (brand.service_area || []).join(', ') || 'ไม่ระบุ'
}

