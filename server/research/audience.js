// ร่างที่หลุดไปมุมคนปล่อยเงิน — จับเฉพาะวลีที่ชัดว่าเป็นมุมคัดลูกค้า/ตั้งวงเงิน (คำอย่าง "นักลงทุน" "นายทุน" "ปล่อยกู้" ใช้เตือนภัยฝั่งเจ้าของทรัพย์ได้ จึงไม่จับ)
// เจอจริง #27 (9 พ.ย. 2569): "หากผู้ขายฝากเป็นบุคคลธรรมดา…" · "ราคาที่รองรับทำเล"
export const LENDER_VIEW_RE = /LTV|ราคาที่รองรับ|ทรัพย์ราคาตก|(?:หาก|ถ้า)ผู้(?:ขายฝาก|จำนอง)(?:เป็น|มี)|ตรวจ(?:สอบ)?(?:ตัว)?ผู้(?:ขายฝาก|จำนอง)/

export function lenderViewHit(text, code) {
  if (code !== 'A') return ''
  const m = LENDER_VIEW_RE.exec(String(text || ''))
  return m ? m[0] : ''
}
